"""Open test rig: a printed tray that holds the PCB on posts with the six
peristaltic pumps around it, so the whole system can be wired up and run
before the real enclosure exists. No lid, no reservoir, no level sensor.

Run:    python case/test_rig.py [rubber|direct]
        The argument picks how the pumps are shown in the viewer and the
        assembly export (default rubber). The rig is the same for both; the
        clearance check runs against both.
View:   open the OCP CAD Viewer panel in VS Code (Ctrl+K V) before running.
Output: case/out/test_rig.{step,stl,3mf} and assembly_<mount>.step, plus the
        STL + STEP of the rig again in case/print/ for a print service.

Coordinates are the KiCad STEP export: X = KiCad x, Y = -KiCad y, Z = 0 at the
underside of the PCB. The front of the device is the board's short edge at
KiCad x = 15 (the OLED reads from there); +Y is the user's left.

Layout:
  * base: a thin plate with lightening windows, standing on four stick-on
    rubber feet.
  * seven posts at the PCB mounting holes, with M3 heat-set inserts on top,
    hold the board high enough for the pump motors to run underneath it.
  * three walls (back, left, right), each carrying two pumps; the front,
    where the display and controls are, stays open. A pump's
    bracket bolts to the outer face, its head (and the tube stubs, pointing
    up) outside the rig, its motor reaching in under the board through a U
    slot that is open at the top: drop the motor in, then fit two screws.
    The slot is wider than the can, so the motor never touches the plastic.
  * pump mounting: two M3 male-male rubber anti-vibration mounts per pump
    (ISO_L long) between the wall and the bracket, through plain holes, so
    rubber is the only contact. Small pads under each motor's free end take
    a strip of foam tape and stop the cantilevered motor sagging on the
    rubber. The same holes also take a direct M3 screw + nut ("direct").
  * pump numbering follows the connectors J9..J14, going round from the
    front left: P1, P2 on the left wall (front, back), P3, P4 on the back
    wall (left, right), P5, P6 on the right wall (back, front).
  * posts only at MH1-MH4 and MH6: the side pumps' motors pass where MH5 and
    MH7 would need theirs.
"""


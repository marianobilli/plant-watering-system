# --- KiCad placement ------------------------------------------------------------
def footprint_positions(pcb_file, rotations=None):
    """Return {reference: (x, y)} in STEP coordinates (Y flipped). If a dict is
    passed as rotations it is filled with {reference: angle}."""
    text = pcb_file.read_text(encoding="utf8")
    pos = {}
    for m in re.finditer(r'\(footprint "[^"]+"\s.*?\(at ([-\d.]+) ([-\d.]+)(?: ([-\d.]+))?\)', text, re.S):
        ref = re.search(r'\(property "Reference" "([^"]+)"', text[m.start():m.start() + 3000])
        if ref:
            pos[ref.group(1)] = (float(m.group(1)), -float(m.group(2)))
            if rotations is not None:
                rotations[ref.group(1)] = float(m.group(3) or 0)
    return pos


def generated_model(module_name, var, loc=None):
    """Build a coloured Compound from a make_*.py part list (footprint frame;
    the generator uses +y down, flipped here as the STEP writer does). loc, a
    Location, is applied to every part."""
    if str(MODELS_DIR) not in sys.path:
        sys.path.insert(0, str(MODELS_DIR))
    model = getattr(importlib.import_module(module_name), var)
    kids = []
    for part in model.parts:
        kind, name, cname = part[:3]
        if kind == "box":
            x0, y0, z0, x1, y1, z1 = part[3:]
            shp = box(x0, -y1, z0, x1, -y0, z1)
        else:  # cyl, axis along z
            cx, cy, r, z0, z1 = part[3:]
            shp = Pos(cx, -cy, z0) * Cylinder(r, z1 - z0, align=(Align.CENTER, Align.CENTER, Align.MIN))
        if loc is not None:
            shp = loc * shp
        shp.label = name
        shp.color = Color(*model.colors[cname])
        kids.append(shp)
    return Compound(children=kids, label=model.name)


def colorize_pcb(pcb):
    """Replace the flattened custom models in the exported assembly with
    coloured rebuilds, rotated by their footprint angle and shifted so each
    bounding box lands on the exported child's."""
    rot = {}
    footprint_positions(KICAD_PCB, rot)
    kids = []
    for child in pcb.children:
        gen = GENERATED_MODELS.get(child.label)
        if not gen:
            kids.append(child)
            continue
        module, var, ref = gen
        angle = rot.get(ref, 0.0)
        rotated = Rot_z(angle) * generated_model(module, var)
        d = child.bounding_box().min - rotated.bounding_box().min
        model = generated_model(module, var, Pos(d.X, d.Y, d.Z) * Rot_z(angle))
        model.label = child.label
        kids.append(model)
    out = Compound(children=kids)
    out.label = pcb.label
    return out


def Rot_z(angle):
    return Location((0, 0, 0), (0, 0, angle))


def parts_of(child):
    """The shapes to test for a top-level child of the PCB assembly."""
    if child.label in GENERATED_MODELS:
        return list(child.children)
    return [child]


def load_pcb():
    """Export the KiCad assembly to STEP if missing or stale, then import it."""
    if not PCB_STEP.exists() or PCB_STEP.stat().st_mtime < KICAD_PCB.stat().st_mtime:
        PCB_STEP.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(
            [str(KICAD_CLI), "pcb", "export", "step", "--subst-models", "--force",
             "-o", str(PCB_STEP), str(KICAD_PCB)],
            check=True,
        )
    pcb = colorize_pcb(import_step(str(PCB_STEP)))
    pcb.label = "pcb"
    return pcb


# --- Helpers ----------------------------------------------------------------------
def box(x0, y0, z0, x1, y1, z1):
    return Pos(min(x0, x1), min(y0, y1), min(z0, z1)) * Box(
        abs(x1 - x0), abs(y1 - y0), abs(z1 - z0), align=Align.MIN)


def zcyl(x, y, d, z0, z1):
    return Pos(x, y, z0) * Cylinder(d / 2, z1 - z0, align=(Align.CENTER, Align.CENTER, Align.MIN))


def bb_touch(a, b):
    """Bounding boxes of two shapes overlap (cheap test before a boolean)."""
    p, q = a.bounding_box(), b.bounding_box()
    return (p.min.X < q.max.X and q.min.X < p.max.X and p.min.Y < q.max.Y and q.min.Y < p.max.Y
            and p.min.Z < q.max.Z and q.min.Z < p.max.Z)


def overlaps(a, b):
    """Axis-aligned rectangles (x0, y0, x1, y1) overlap."""
    return a[0] < b[2] and b[0] < a[2] and a[1] < b[3] and b[1] < a[3]


# --- Pumps --------------------------------------------------------------------------
def pump_parts():
    """The pump in its own frame (see PUMP_*), as {name: shape}."""
    hw, hh = PUMP_BRACKET_W / 2, PUMP_BRACKET_H / 2
    f, e = PUMP_BRACKET_FLAT / 2, PUMP_BRACKET_END / 2
    outline = Polygon((f, hh), (hw, e), (hw, -e), (f, -hh), (-f, -hh), (-hw, -e), (-hw, e), (-f, hh), align=None)
    bracket = extrude(outline, amount=PUMP_BRACKET_T, dir=(0, 0, 1))
    for x in (-PUMP_HOLE_X, PUMP_HOLE_X):
        bracket -= zcyl(x, 0, PUMP_HOLE_D, -1, PUMP_BRACKET_T + 1)
    z0, z1 = PUMP_BRACKET_T, PUMP_BRACKET_T + PUMP_HEAD_L
    head = zcyl(0, PUMP_HEAD_Y, PUMP_HEAD_D, z0, z1)
    head += box(-PUMP_BLOCK_W / 2, PUMP_BLOCK_Y0, z0, PUMP_BLOCK_W / 2, hh, z1)
    tz = z1 - PUMP_TUBE_Z
    tubes = None
    for x in (-PUMP_TUBE_X, PUMP_TUBE_X):
        t = Pos(x, hh, tz) * Rot_x(-90) * Cylinder(PUMP_TUBE_D / 2, PUMP_TUBE_L,
                                                     align=(Align.CENTER, Align.CENTER, Align.MIN))
        tubes = t if tubes is None else tubes + t
    motor = zcyl(0, 0, PUMP_MOTOR_D, -PUMP_MOTOR_L, 0)
    motor += zcyl(0, 0, PUMP_BOSS_D, -PUMP_MOTOR_L - PUMP_BOSS_L, -PUMP_MOTOR_L)
    terms = None
    for x in (-PUMP_TERM_X, PUMP_TERM_X):
        t = box(x - 1.5, -0.5, -PUMP_MOTOR_L - PUMP_TERM_L, x + 1.5, 0.5, -PUMP_MOTOR_L)
        terms = t if terms is None else terms + t
    return {"bracket": bracket, "head": head, "tube": tubes, "motor": motor, "terminal": terms}


def Rot_x(angle):
    return Location((0, 0, 0), (angle, 0, 0))


def pump_location(origin, ly, lz):
    """Location mapping the pump frame to the world: origin, tube direction
    ly and shaft direction lz (head outwards); x follows as y cross z."""
    ly, lz = Vector(*ly), Vector(*lz)
    return Location(Plane(origin=origin, x_dir=ly.cross(lz), z_dir=lz))


def pump_mounts():
    """(name, wall, along, outward normal) for the six pumps: 'along' is the
    pump centre along its wall (Y for the back wall, X for the side walls)."""
    return [
        ("P1", "left", SIDE_PUMPS_X[0], (0, 1, 0)),
        ("P2", "left", SIDE_PUMPS_X[1], (0, 1, 0)),
        ("P3", "back", BACK_PUMPS_Y[0], (1, 0, 0)),
        ("P4", "back", BACK_PUMPS_Y[1], (1, 0, 0)),
        ("P5", "right", SIDE_PUMPS_X[1], (0, -1, 0)),
        ("P6", "right", SIDE_PUMPS_X[0], (0, -1, 0)),
    ]


def wall_point(wall, along, offset=0.0):
    """Point on the pump axis at the wall's outer face, moved offset outwards."""
    if wall == "back":
        return (BACK_X + offset, along, PUMP_Z)
    if wall == "left":
        return (along, LEFT_Y + offset, PUMP_Z)
    return (along, RIGHT_Y - offset, PUMP_Z)


def pumps(mount):
    """All six pumps placed for 'rubber' (bracket ISO_L off the wall on rubber
    mounts) or 'direct' (bracket flat on the wall), with the rubber mounts."""
    gap = ISO_L if mount == "rubber" else 0.0
    parts = pump_parts()
    kids = []
    for name, wall, along, n in pump_mounts():
        loc = pump_location(wall_point(wall, along, gap), (0, 0, 1), n)
        for pname, shp in parts.items():
            s = loc * shp
            s.label = f"{name} {pname}"
            s.color = Color(COLORS[pname])
            kids.append(s)
        if mount == "rubber":
            for x in (-PUMP_HOLE_X, PUMP_HOLE_X):
                r = loc * zcyl(x, 0, ISO_D, -ISO_L, 0)
                r.label = f"{name} rubber mount"
                r.color = Color(COLORS["rubber"])
                kids.append(r)
    return Compound(children=kids, label=f"pumps ({mount})")


# --- Rig ------------------------------------------------------------------------------
def build():
    fp = footprint_positions(KICAD_PCB)
    holes = [fp[r] for r in MOUNT_HOLES]
    x0, x1 = FRONT_X, BACK_X
    y0, y1 = RIGHT_Y, LEFT_Y

    rig = box(x0, y0, BASE_BOT, x1, y1, BASE_TOP)
    rig = fillet(rig.edges().filter_by(Axis.Z), CORNER_R)

    # Walls with a U slot per pump, open at the top, and the two mount holes.
    rig += box(x1 - WALL_T, y0, BASE_TOP - 0.01, x1, y1, WALL_TOP)
    rig += box(x0, y1 - WALL_T, BASE_TOP - 0.01, x1, y1, WALL_TOP)
    rig += box(x0, y0, BASE_TOP - 0.01, x1, y0 + WALL_T, WALL_TOP)
    pads = []
    for _, wall, along, n in pump_mounts():
        loc = pump_location(wall_point(wall, along), (0, 0, 1), n)
        # In the pump frame the wall runs from z = -WALL_T to 0; cut through it.
        slot = Pos(0, 0, -WALL_T - 1) * Cylinder(SLOT_W / 2, WALL_T + 2, align=(Align.CENTER, Align.CENTER, Align.MIN))
        slot += box(-SLOT_W / 2, 0, -WALL_T - 1, SLOT_W / 2, 60, 1)
        rig -= loc * slot
        for x in (-PUMP_HOLE_X, PUMP_HOLE_X):
            rig -= loc * zcyl(x, 0, MOUNT_HOLE_D, -WALL_T - 1, 1)
        # Pad under the motor's free end (rubber layout), for foam tape.
        end = ISO_L - PUMP_MOTOR_L                     # motor end cap, pump frame z, rubber layout
        pz0, pz1 = end + PAD_FROM_END, end + PAD_FROM_END + PAD_L
        top = -PUMP_MOTOR_D / 2 - PAD_GAP
        pad = loc * box(-PAD_W / 2, BASE_TOP - PUMP_Z - 0.01, pz0, PAD_W / 2, top, pz1)
        rig += pad
        bb = pad.bounding_box()
        pads.append((bb.min.X, bb.min.Y, bb.max.X, bb.max.Y))

    # Posts with heat-set inserts.
    for x, y in holes:
        rig += zcyl(x, y, POST_FOOT_D, BASE_TOP - 0.01, BASE_TOP + POST_FOOT_H)
        rig += zcyl(x, y, POST_D, BASE_TOP, 0.0)
        rig -= zcyl(x, y, INSERT_D, -INSERT_DEPTH, 0.1)

    # Lightening windows in the base.
    keep = [(x - POST_FOOT_D / 2 - 2, y - POST_FOOT_D / 2 - 2, x + POST_FOOT_D / 2 + 2, y + POST_FOOT_D / 2 + 2)
            for x, y in holes]
    keep += [(a - 2, b - 2, c + 2, d + 2) for a, b, c, d in pads]
    ix0, ix1 = x0 + WIN_KEEP, x1 - WIN_KEEP
    iy0, iy1 = y0 + WIN_KEEP, y1 - WIN_KEEP
    nx = int((ix1 - ix0 + WIN_RIB) // (WIN + WIN_RIB))
    ny = int((iy1 - iy0 + WIN_RIB) // (WIN + WIN_RIB))
    sx = ix0 + (ix1 - ix0 - (nx * WIN + (nx - 1) * WIN_RIB)) / 2
    sy = iy0 + (iy1 - iy0 - (ny * WIN + (ny - 1) * WIN_RIB)) / 2
    for i in range(nx):
        for j in range(ny):
            wx, wy = sx + i * (WIN + WIN_RIB), sy + j * (WIN + WIN_RIB)
            r = (wx, wy, wx + WIN, wy + WIN)
            if any(overlaps(r, k) for k in keep):
                continue
            rig -= extrude(Pos(wx + WIN / 2, wy + WIN / 2, BASE_BOT - 0.1) * RectangleRounded(WIN, WIN, WIN_R),
                           amount=BASE_T + 0.2)

    # Version engraved in the underside, mirrored so it reads with the rig upside down.
    if ENGRAVE_TEXT:
        txt = Text(ENGRAVE_TEXT, ENGRAVE_SIZE, align=(Align.CENTER, Align.CENTER)).mirror(Plane.XZ)
        txt = Pos((x0 + x1) / 2, y0 + WIN_KEEP / 2 + 1.5, BASE_BOT - 0.01) * txt
        rig -= extrude(txt, amount=ENGRAVE_DEPTH + 0.01)
    return rig


def check_clearance(pcb, rig, pump_sets):
    """Report overlaps: rig and every pump set against the PCB assembly
    (leads clipped at -LEAD_TRIM), and each pump set against the rig and
    against itself. The rubber mounts are expected to touch the wall.
    Returns True if clear."""
    problems = []
    bb = pcb.bounding_box()
    keep = box(bb.min.X - 1, bb.min.Y - 1, -LEAD_TRIM, bb.max.X + 1, bb.max.Y + 1, bb.max.Z + 1)
    pcb_parts = []
    for top in pcb.children:
        for child in parts_of(top):
            clipped = child & keep
            if clipped.solids():
                label = child.label if child is top else f"{top.label}/{child.label}"
                pcb_parts.append((label, clipped))
    for label, part in pcb_parts:
        v = (rig & part).volume if bb_touch(rig, part) else 0
        if v > 0.01:
            problems.append(f"  rig intersects {label}: {v:.2f} mm^3")
    for ps in pump_sets:
        solid = [c for c in ps.children if "rubber" not in c.label]
        for c in solid:
            v = (rig & c).volume if bb_touch(rig, c) else 0
            if v > 0.01:
                problems.append(f"  rig intersects {c.label} ({ps.label}): {v:.2f} mm^3")
            for label, part in pcb_parts:
                v = (c & part).volume if bb_touch(c, part) else 0
                if v > 0.01:
                    problems.append(f"  {c.label} ({ps.label}) intersects {label}: {v:.2f} mm^3")
        for i, a in enumerate(solid):
            for b in solid[i + 1:]:
                if a.label.split()[0] != b.label.split()[0] and bb_touch(a, b) and (a & b).volume > 0.01:
                    problems.append(f"  {a.label} intersects {b.label} ({ps.label})")
    print("clearance check:", "OK" if not problems else "")
    for p in problems:
        print(p)
    return not problems


def export(rig, pcb, pump_set):
    OUT.mkdir(exist_ok=True)
    PRINT.mkdir(exist_ok=True)
    for folder in (OUT, PRINT):
        export_step(rig, str(folder / "test_rig.step"))
        export_stl(rig, str(folder / "test_rig.stl"))
    mesher = Mesher()
    mesher.add_shape(rig)
    mesher.write(str(OUT / "test_rig.3mf"))
    mount = pump_set.label.split("(")[1].rstrip(")")
    asm = Compound(children=[pcb, rig, pump_set], label=f"plant_watering_test_rig_{mount}")
    export_step(asm, str(OUT / f"assembly_{mount}.step"))


